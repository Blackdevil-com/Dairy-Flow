from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.pdfgen import canvas

from app.models.sales import Invoice
from app.models.business import BusinessSettings

class NumberedCanvas(canvas.Canvas):
    """Canvas that draws header, footer and DEMO watermark if applicable."""
    def __init__(self, *args, **kwargs):
        super(NumberedCanvas, self).__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super(NumberedCanvas, self).showPage()
        super(NumberedCanvas, self).save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        
        # DEMO Watermark
        if getattr(self, "is_demo", True):
            self.setFont("Helvetica-Bold", 54)
            self.setFillColor(colors.HexColor("#FFCCCC"), alpha=0.35)
            self.translate(300, 400)
            self.rotate(45)
            self.drawCentredString(0, 0, "DEMO - NOT A TAX INVOICE")
            self.restoreState()
            self.saveState()

        # Footer
        self.setFont("Helvetica", 9)
        self.setFillColor(colors.HexColor("#666666"))
        self.drawString(54, 36, f"Generated by DairyFlow ERP | Page {self._pageNumber} of {page_count}")
        self.drawRightString(612 - 54, 36, "Authoritative Database Copy")
        self.restoreState()


def generate_invoice_pdf(invoice: Invoice, business: Optional[BusinessSettings], output_path: str):
    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    doc = SimpleDocTemplate(
        output_path,
        pagesize=letter,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=50
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Heading1"],
        fontName="Helvetica-Bold",
        fontSize=20,
        textColor=colors.HexColor("#004D40"),  # Deep teal
        spaceAfter=6
    )
    subtitle_style = ParagraphStyle(
        "DocSubTitle",
        parent=styles["Normal"],
        fontName="Helvetica",
        fontSize=10,
        textColor=colors.HexColor("#444444"),
        spaceAfter=15
    )
    header_style = ParagraphStyle(
        "TableHeader",
        fontName="Helvetica-Bold",
        fontSize=9,
        textColor=colors.whitesmoke,
        alignment=1
    )
    cell_style = ParagraphStyle(
        "TableCell",
        fontName="Helvetica",
        fontSize=9,
        textColor=colors.HexColor("#222222")
    )
    cell_right = ParagraphStyle(
        "TableCellRight",
        fontName="Helvetica",
        fontSize=9,
        textColor=colors.HexColor("#222222"),
        alignment=2
    )

    story = []

    # Business Header
    b_name = business.business_name if business else "DairyFlow Co-operative"
    b_trade = business.trade_name if business else "DairyFlow Depot"
    b_addr = business.address if business and business.address else "Central Dairy Warehouse, Maharashtra"
    b_phone = business.phone if business and business.phone else "+91 9876543210"

    story.append(Paragraph(b_name, title_style))
    story.append(Paragraph(f"{b_trade} | Address: {b_addr} | Contact: {b_phone}", subtitle_style))
    
    # Document Type Banner
    doc_banner = "DEMO COMMERCIAL RECEIPT" if invoice.is_demo_watermark else invoice.doc_type.replace("_", " ")
    banner_color = "#D32F2F" if invoice.is_demo_watermark else "#004D40"
    banner_style = ParagraphStyle(
        "DocBanner",
        fontName="Helvetica-Bold",
        fontSize=13,
        textColor=colors.HexColor(banner_color),
        spaceAfter=10
    )
    story.append(Paragraph(f"<b>DOCUMENT: {doc_banner}</b>", banner_style))

    # Meta Table (Invoice & Customer details)
    cust_name = invoice.customer_name_snap
    cust_phone = invoice.customer_phone_snap or "N/A"
    cust_addr = invoice.customer_address_snap or "N/A"
    
    meta_data = [
        [
            Paragraph(f"<b>Invoice No:</b> {invoice.invoice_no}<br/><b>Date:</b> {invoice.invoice_date}<br/><b>Status:</b> {invoice.payment_status}", cell_style),
            Paragraph(f"<b>Billed To:</b> {cust_name}<br/><b>Phone:</b> {cust_phone}<br/><b>Address:</b> {cust_addr}", cell_style)
        ]
    ]
    meta_table = Table(meta_data, colWidths=[260, 272])
    meta_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,-1), colors.HexColor("#F5F9F8")),
        ('BOX', (0,0), (-1,-1), 1, colors.HexColor("#004D40")),
        ('VALIGN', (0,0), (-1,-1), 'TOP'),
        ('PADDING', (0,0), (-1,-1), 8),
    ]))
    story.append(meta_table)
    story.append(Spacer(1, 15))

    # Items Table
    table_data = [
        [
            Paragraph("Item & Description", header_style),
            Paragraph("HSN", header_style),
            Paragraph("Qty", header_style),
            Paragraph("Rate (₹)", header_style),
            Paragraph("Tax Rate", header_style),
            Paragraph("Total (₹)", header_style)
        ]
    ]

    for item in invoice.items:
        table_data.append([
            Paragraph(item.product_name_snap, cell_style),
            Paragraph(item.hsn_snap, cell_style),
            Paragraph(f"{item.billed_qty:.2f} {item.unit_code}", cell_right),
            Paragraph(f"{item.unit_price_snap:.2f}", cell_right),
            Paragraph(f"{item.tax_rate_snap:.1f}%", cell_right),
            Paragraph(f"{item.line_total:.2f}", cell_right)
        ])

    items_table = Table(table_data, colWidths=[180, 50, 75, 75, 65, 87])
    items_table.setStyle(TableStyle([
        ('BACKGROUND', (0,0), (-1,0), colors.HexColor("#004D40")),
        ('GRID', (0,0), (-1,-1), 0.5, colors.HexColor("#CCCCCC")),
        ('VALIGN', (0,0), (-1,-1), 'MIDDLE'),
        ('PADDING', (0,0), (-1,-1), 6),
    ]))
    story.append(items_table)
    story.append(Spacer(1, 12))

    # Totals Summary
    summary_data = [
        ["Subtotal:", f"₹ {invoice.subtotal:.2f}"],
        ["Demo Tax (GST Watermarked):", f"₹ {invoice.total_tax:.2f}"],
        ["Discount:", f"- ₹ {invoice.discount:.2f}"],
        ["Total Payable:", f"₹ {invoice.total_amount:.2f}"],
        ["Amount Paid:", f"₹ {invoice.paid_amount:.2f}"],
        ["Outstanding Balance:", f"₹ {invoice.outstanding_amount:.2f}"]
    ]
    summary_table = Table(summary_data, colWidths=[400, 132])
    summary_table.setStyle(TableStyle([
        ('ALIGN', (0,0), (-1,-1), 'RIGHT'),
        ('FONTNAME', (0,0), (-1,-1), 'Helvetica'),
        ('FONTSIZE', (0,0), (-1,-1), 9),
        ('FONTNAME', (0,3), (-1,3), 'Helvetica-Bold'),
        ('FONTNAME', (0,-1), (-1,-1), 'Helvetica-Bold'),
        ('TEXTCOLOR', (0,-1), (-1,-1), colors.HexColor("#D32F2F") if invoice.outstanding_amount > 0 else colors.HexColor("#00796B")),
        ('PADDING', (0,0), (-1,-1), 3),
    ]))
    story.append(summary_table)

    # Build document with custom canvas
    def canvas_maker(*args, **kwargs):
        c = NumberedCanvas(*args, **kwargs)
        c.is_demo = invoice.is_demo_watermark
        return c

    doc.build(story, canvasmaker=canvas_maker)
    return output_path
